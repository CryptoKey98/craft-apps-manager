#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Icon {
    Info,
    Activity,
    Sun,
    Gear,
    Search,
    Grid,
    Download,
    Refresh,
    Rollback,
    Play,
    Trash,
    ArrowUp,
    ChevronDown,
    ChevronRight,
    Close,
    Sliders,
    Archive,
    Layers,
    Code,
    Hammer,
    Alert,
    Folder,
    Check,
    EyeOff,
    Eye,
}

/// Strokes an icon drawn on the 24-unit grid the mockups use, scaled into `rect`.
pub fn paint_icon(painter: &egui::Painter, rect: Rect, icon: Icon, color: Color32) {
    paint_icon_weight(painter, rect, icon, color, 2.0);
}

/// Like `paint_icon` with a stroke of `weight` grid units (the mockups use 2, and
/// 2.5 for the small arrow in the update pill).
pub fn paint_icon_weight(
    painter: &egui::Painter,
    rect: Rect,
    icon: Icon,
    color: Color32,
    weight: f32,
) {
    let scale = rect.width().min(rect.height()) / 24.0;
    let origin = rect.center() - Vec2::splat(12.0 * scale);
    let p = |x: f32, y: f32| origin + egui::vec2(x, y) * scale;
    let stroke = Stroke::new((weight * scale).max(1.2), color);
    let line = |points: Vec<Pos2>| {
        painter.add(egui::Shape::line(points, stroke));
    };
    let arc = |cx: f32, cy: f32, r: f32, from: f32, to: f32| -> Vec<Pos2> {
        let steps = ((to - from).abs() / 12.0).ceil().max(2.0) as usize;
        (0..=steps)
            .map(|i| {
                let a = (from + (to - from) * i as f32 / steps as f32).to_radians();
                p(cx + r * a.cos(), cy + r * a.sin())
            })
            .collect()
    };
    match icon {
        Icon::Rollback => {
            let mut circle = arc(12.0, 12.0, 8.0, 160.0, -135.0);
            circle.push(p(3.0, 9.0));
            line(circle);
            line(vec![p(3.0, 3.0), p(3.0, 9.0), p(9.0, 9.0)]);
        }
        Icon::Hammer => {
            for (points, closed) in HAMMER {
                let points: Vec<_> = points.iter().map(|&[x, y]| p(x, y)).collect();
                if *closed {
                    painter.add(egui::Shape::closed_line(points, stroke));
                } else {
                    if let (Some(first), Some(last)) = (points.first(), points.last()) {
                        painter.circle_filled(*first, stroke.width * 0.5, color);
                        painter.circle_filled(*last, stroke.width * 0.5, color);
                    }
                    line(points);
                }
            }
        }
        Icon::Activity => line(vec![
            p(2.0, 12.0),
            p(6.0, 12.0),
            p(9.0, 4.0),
            p(13.0, 20.0),
            p(16.0, 10.0),
            p(18.0, 12.0),
            p(22.0, 12.0),
        ]),
        Icon::EyeOff | Icon::Eye => {
            line(vec![
                p(2.0, 12.0),
                p(6.0, 7.0),
                p(12.0, 5.0),
                p(18.0, 7.0),
                p(22.0, 12.0),
                p(18.0, 17.0),
                p(12.0, 19.0),
                p(6.0, 17.0),
                p(2.0, 12.0),
            ]);
            painter.circle_stroke(p(12.0, 12.0), 3.0 * scale, stroke);
            if matches!(icon, Icon::EyeOff) {
                line(vec![p(3.0, 3.0), p(21.0, 21.0)]);
            }
        }
        Icon::Sun => {
            painter.circle_stroke(p(12.0, 12.0), 4.0 * scale, stroke);
            for angle in (0..360).step_by(45) {
                let angle = (angle as f32).to_radians();
                line(vec![
                    p(12.0 + 7.0 * angle.cos(), 12.0 + 7.0 * angle.sin()),
                    p(12.0 + 10.0 * angle.cos(), 12.0 + 10.0 * angle.sin()),
                ]);
            }
        }
        Icon::Gear => {
            painter.circle_stroke(p(12.0, 12.0), 3.0 * scale, stroke);
            let outline = GEAR
                .as_chunks::<2>()
                .0
                .iter()
                .map(|&[x, y]| p(x, y))
                .collect();
            painter.add(egui::Shape::closed_line(outline, stroke));
        }
        Icon::Search => {
            painter.circle_stroke(p(11.0, 11.0), 7.5 * scale, stroke);
            line(vec![p(16.5, 16.5), p(21.0, 21.0)]);
        }
        Icon::Grid => {
            for (x, y) in [(3.0, 3.0), (14.0, 3.0), (3.0, 14.0), (14.0, 14.0)] {
                painter.rect_stroke(
                    Rect::from_min_max(p(x, y), p(x + 7.0, y + 7.0)),
                    CornerRadius::same((1.5 * scale) as u8),
                    stroke,
                    StrokeKind::Middle,
                );
            }
        }
        Icon::ChevronDown => line(vec![p(6.0, 9.0), p(12.0, 15.0), p(18.0, 9.0)]),
        Icon::ChevronRight => line(vec![p(9.0, 6.0), p(15.0, 12.0), p(9.0, 18.0)]),
        Icon::Download => {
            line(vec![
                p(3.0, 15.0),
                p(3.0, 19.0),
                p(5.0, 21.0),
                p(19.0, 21.0),
                p(21.0, 19.0),
                p(21.0, 15.0),
            ]);
            line(vec![p(7.0, 10.0), p(12.0, 15.0), p(17.0, 10.0)]);
            line(vec![p(12.0, 15.0), p(12.0, 3.0)]);
        }
        Icon::Refresh => {
            line(arc(12.0, 12.0, 9.0, 0.0, 312.0));
            line(vec![p(18.0, 5.3), p(21.0, 8.0)]);
            line(vec![p(21.0, 3.0), p(21.0, 8.0), p(16.0, 8.0)]);
        }
        Icon::Play => {
            painter.add(egui::Shape::closed_line(
                vec![p(6.0, 3.0), p(20.0, 12.0), p(6.0, 21.0)],
                stroke,
            ));
        }
        Icon::Trash => {
            line(vec![p(3.0, 6.0), p(21.0, 6.0)]);
            line(vec![
                p(19.0, 6.0),
                p(19.0, 20.0),
                p(17.0, 22.0),
                p(7.0, 22.0),
                p(5.0, 20.0),
                p(5.0, 6.0),
            ]);
            line(vec![
                p(8.0, 6.0),
                p(8.0, 4.0),
                p(10.0, 2.0),
                p(14.0, 2.0),
                p(16.0, 4.0),
                p(16.0, 6.0),
            ]);
        }
        Icon::ArrowUp => {
            line(vec![p(12.0, 19.0), p(12.0, 5.0)]);
            line(vec![p(5.0, 12.0), p(12.0, 5.0), p(19.0, 12.0)]);
        }
        Icon::Close => {
            line(vec![p(18.0, 6.0), p(6.0, 18.0)]);
            line(vec![p(6.0, 6.0), p(18.0, 18.0)]);
        }
        Icon::Sliders => {
            for (x, a, b, c) in [
                (4.0, 21.0, 14.0, 10.0),
                (12.0, 21.0, 12.0, 8.0),
                (20.0, 21.0, 16.0, 12.0),
            ] {
                line(vec![p(x, a), p(x, b)]);
                line(vec![p(x, c), p(x, 3.0)]);
            }
            line(vec![p(1.0, 14.0), p(7.0, 14.0)]);
            line(vec![p(9.0, 8.0), p(15.0, 8.0)]);
            line(vec![p(17.0, 16.0), p(23.0, 16.0)]);
        }
        Icon::Layers => {
            line(vec![
                p(2.0, 8.0),
                p(12.0, 3.0),
                p(22.0, 8.0),
                p(12.0, 13.0),
                p(2.0, 8.0),
            ]);
            line(vec![p(2.0, 13.0), p(12.0, 18.0), p(22.0, 13.0)]);
            line(vec![p(2.0, 18.0), p(12.0, 23.0), p(22.0, 18.0)]);
        }
        Icon::Archive => {
            painter.rect_stroke(
                Rect::from_min_max(p(2.0, 3.0), p(22.0, 8.0)),
                CornerRadius::same(scale as u8),
                stroke,
                StrokeKind::Middle,
            );
            line(vec![
                p(4.0, 8.0),
                p(4.0, 19.0),
                p(6.0, 21.0),
                p(18.0, 21.0),
                p(20.0, 19.0),
                p(20.0, 8.0),
            ]);
            line(vec![p(10.0, 12.0), p(14.0, 12.0)]);
        }
        Icon::Code => {
            line(vec![p(16.0, 18.0), p(22.0, 12.0), p(16.0, 6.0)]);
            line(vec![p(8.0, 6.0), p(2.0, 12.0), p(8.0, 18.0)]);
        }
        Icon::Alert => {
            painter.circle_stroke(p(12.0, 12.0), 10.0 * scale, stroke);
            line(vec![p(12.0, 8.0), p(12.0, 12.5)]);
            painter.circle_filled(p(12.0, 16.0), 1.2 * scale, color);
        }
        Icon::Info => {
            painter.circle_stroke(p(12.0, 12.0), 10.0 * scale, stroke);
            painter.circle_filled(p(12.0, 7.0), 1.1 * scale, color);
            line(vec![p(12.0, 11.0), p(12.0, 17.0)]);
        }
        Icon::Folder => {
            painter.add(egui::Shape::closed_line(
                vec![
                    p(2.0, 5.0),
                    p(9.0, 5.0),
                    p(11.0, 7.5),
                    p(22.0, 7.5),
                    p(22.0, 20.0),
                    p(2.0, 20.0),
                ],
                stroke,
            ));
        }
        Icon::Check => line(vec![p(20.0, 6.0), p(9.0, 17.0), p(4.0, 12.0)]),
    }
}


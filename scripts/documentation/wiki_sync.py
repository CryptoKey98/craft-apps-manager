"""Ownership-safe local wiki reconciliation. No credentials or public Git transport."""
import hashlib
import json
from pathlib import Path
import re

from wiki import OWNERSHIP, REPOSITORY, checked_path, linked


def output_name(name, metadata=False):
    if not isinstance(name, str) or not (
        re.fullmatch(r'[A-Za-z0-9-]+\.md', name)
        or name in ('_Sidebar.md', '_Footer.md')
        or re.fullmatch(r'images/[A-Za-z0-9-]+\.png', name)
        or (metadata and name == OWNERSHIP)
    ):
        raise ValueError('Invalid managed wiki filename: ' + repr(name))


def validate_ownership(record):
    if not isinstance(record, dict) or type(record.get('schema')) is not int or record['schema'] != 1 or record.get('repository') != REPOSITORY:
        raise ValueError('Invalid wiki ownership scope/schema')
    if not re.fullmatch(r'[0-9a-f]{40}', record.get('source_commit', '')):
        raise ValueError('Invalid ownership source commit')
    if not isinstance(record.get('files'), dict) or not 1 <= len(record['files']) <= 512:
        raise ValueError('Invalid owned files')
    seen = set()
    for name, digest in record['files'].items():
        output_name(name)
        if name.casefold() in seen or not isinstance(digest, str) or not re.fullmatch('[0-9a-f]{64}', digest):
            raise ValueError('Invalid/colliding owned file identity')
        seen.add(name.casefold())


def digest(path):
    if path.exists() and not path.is_file():
        raise ValueError('Managed path is not a regular file: ' + str(path))
    return hashlib.sha256(path.read_bytes()).hexdigest() if path.is_file() else None


def plan_changes(checkout, generated, previous_manifest, adopt):
    checkout = Path(checkout).absolute()
    if linked(checkout) or not checkout.is_dir():
        raise ValueError('Wiki checkout must be a real directory')
    if OWNERSHIP not in generated:
        raise ValueError('Missing generated ownership')
    next_record = json.loads(generated[OWNERSHIP])
    validate_ownership(next_record)
    if set(next_record['files']) != set(generated) - {OWNERSHIP}:
        raise ValueError('Generated file list does not match ownership')
    for name, body in generated.items():
        output_name(name, metadata=True)
        checked_path(checkout, name)
        if not isinstance(body, bytes) or (name != OWNERSHIP and hashlib.sha256(body).hexdigest() != next_record['files'][name]):
            raise ValueError('Generated bytes do not match ownership')
    record_path = checked_path(checkout, OWNERSHIP)
    if record_path.exists():
        actual = json.loads(record_path.read_text(encoding='utf-8'))
        if actual != previous_manifest:
            raise ValueError('Existing ownership must be explicitly loaded and validated')
    elif previous_manifest is not None:
        raise ValueError('Missing ownership record')
    elif any(p.is_file() and b'<!-- Generated from repository documentation;' in p.read_bytes()[:128]
             for p in checkout.glob('*.md') if not linked(p)):
        raise ValueError('Generated wiki is missing its ownership record')
    old = {}
    if previous_manifest is not None:
        validate_ownership(previous_manifest)
        old = previous_manifest['files']
    names = set(old) | set(generated)
    if len({name.casefold() for name in names}) != len(names):
        raise ValueError('Case-only wiki filename changes require explicit resolution')
    conflicts, writes, deletes, snapshot = [], {}, [], {}
    for name in set(old) | set(generated):
        output_name(name, metadata=True)
        path = checked_path(checkout, name)
        current = snapshot[name] = digest(path)
        if name in old and current != old[name]:
            conflicts.append('Generated file was edited or removed: ' + name)
        elif name not in old and name != OWNERSHIP and current is not None and name not in adopt:
            conflicts.append('Unowned file collides with wiki output: ' + name)
        if name in generated and current != hashlib.sha256(generated[name]).hexdigest():
            writes[name] = generated[name]
        elif name not in generated and name in old and current is not None:
            deletes.append(name)
    for name in adopt:
        output_name(name)
        if name not in generated or name in old or snapshot.get(name) is None:
            raise ValueError('Adoption must name an existing unowned generated destination')
    return {'writes': writes, 'deletes': sorted(deletes), 'conflicts': sorted(conflicts),
            'snapshot': snapshot, 'checkout': str(checkout)}


def apply_changes(checkout, changes):
    checkout = Path(checkout).absolute()
    if changes['checkout'] != str(checkout) or changes['conflicts']:
        raise ValueError('Wiki sync conflicts; no files changed')
    # Preflight every input again before any write/delete. A plan is not a lock.
    for name, expected in changes['snapshot'].items():
        output_name(name, metadata=True)
        if digest(checked_path(checkout, name)) != expected:
            raise ValueError('Wiki changed after planning: ' + name)
    for name, body in sorted(changes['writes'].items(), key=lambda item: item[0] == OWNERSHIP):
        path = checked_path(checkout, name)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(body)
    for name in changes['deletes']:
        checked_path(checkout, name).unlink()
